/**
 * Writes src/generated/cloud-operations.ts from specs/cloud-api/operations-v1.json:
 * each operation's name, summary, scope, policy, route and input schema. The
 * CLI builds one command per operation from it (`hypequery <group> <action>`).
 *
 *   node scripts/generate-cloud-operations.mjs          regenerate
 *   node scripts/generate-cloud-operations.mjs --check  exit 1 if the committed file is stale
 *
 * Refresh the spec with `pnpm --filter @hypequery/cloud-client spec:update`, then run this.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SPEC_PATH = fileURLToPath(new URL('../../../specs/cloud-api/operations-v1.json', import.meta.url));
const GENERATED_PATH = fileURLToPath(new URL('../src/generated/cloud-operations.ts', import.meta.url));

/** JSON Schema keywords that carry no meaning for flags or docs. */
const DROPPED_KEYS = new Set(['$schema']);

function strip(value) {
  if (Array.isArray(value)) return value.map(strip);
  if (value === null || typeof value !== 'object') return value;
  return Object.fromEntries(
    Object.entries(value).filter(([key]) => !DROPPED_KEYS.has(key)).map(([key, entry]) => [key, strip(entry)]),
  );
}

function renderCloudOperations(spec) {
  if (spec?.kind === undefined || !Array.isArray(spec.operations)) {
    throw new Error('operations-v1.json has no operations array.');
  }
  const operations = spec.operations.map((operation) => ({
    name: operation.name,
    summary: operation.summary,
    scope: operation.scope,
    capability: operation.capability,
    destructive: operation.destructive,
    connector: operation.connector !== false,
    method: operation.http.method,
    path: operation.http.path,
    input: strip(operation.input),
  }));
  return [
    '// Generated by packages/cli/scripts/generate-cloud-operations.mjs from specs/cloud-api/operations-v1.json.',
    '// Do not edit by hand: run `pnpm --filter @hypequery/cli cloud-operations:generate`.',
    '',
    "import type { CloudOperationSpec } from '../utils/cloud-operations/spec-types.js';",
    '',
    `export const CLOUD_OPERATIONS_SPEC_VERSION = ${JSON.stringify(spec.version)};`,
    '',
    `export const CLOUD_OPERATION_SPECS: readonly CloudOperationSpec[] = ${JSON.stringify(operations, null, 2)};`,
    '',
  ].join('\n');
}

const source = renderCloudOperations(JSON.parse(readFileSync(SPEC_PATH, 'utf8')));

if (process.argv.includes('--check')) {
  if (readFileSync(GENERATED_PATH, 'utf8') !== source) {
    console.error('src/generated/cloud-operations.ts is stale. Run `pnpm --filter @hypequery/cli cloud-operations:generate`.');
    process.exit(1);
  }
  console.log('src/generated/cloud-operations.ts is up to date.');
} else {
  writeFileSync(GENERATED_PATH, source);
  console.log(`Wrote ${GENERATED_PATH}`);
}
