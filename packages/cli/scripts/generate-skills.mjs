#!/usr/bin/env node
// Copy the repository's agent skills (skills/<name>/SKILL.md) to where they
// ship: the CLI, which ships only dist/, embeds them in
// src/templates/skills.generated.ts, and the Claude Code plugin carries them in
// plugins/claude-code/hypequery/skills/. Run after editing a skill; `--check`
// exits 1 on drift and writes nothing.
//
// Skill directory names must match SKILL_NAME, and the script never follows a
// symbolic link: it refuses one anywhere it reads, writes or deletes, so a
// link can't make it read or overwrite files outside the repository.
import { lstat, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repository = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const root = path.join(repository, 'skills');
const output = path.join(repository, 'packages', 'cli', 'src', 'templates', 'skills.generated.ts');
const pluginSkills = path.join(repository, 'plugins', 'claude-code', 'hypequery', 'skills');
const check = process.argv.includes('--check');

const SKILL_NAME = /^[a-z0-9][a-z0-9-]*$/;

function fail(message) {
  console.error(message);
  process.exit(1);
}

const relative = target => path.relative(repository, target);
const missing = error => (error.code === 'ENOENT' ? undefined : Promise.reject(error));

/** Fails if `target`, or any directory between the repository and it, is a symbolic link. */
async function refuseSymlinks(target) {
  let current = repository;
  for (const part of relative(target).split(path.sep).filter(Boolean)) {
    current = path.join(current, part);
    const stats = await lstat(current).catch(missing);
    if (!stats) return;
    if (stats.isSymbolicLink()) {
      fail(`${relative(current)} is a symbolic link; generate-skills.mjs does not follow links. Replace it with a real file or directory.`);
    }
  }
}

// Dotfiles (.DS_Store, editor state) are not skills, here or in the plugin.
const visible = entry => !entry.name.startsWith('.');

/** Skill directories in `directory`, refusing links and names that don't match SKILL_NAME. */
async function skillDirectories(directory, { filesAllowed }) {
  await refuseSymlinks(directory);
  const entries = ((await readdir(directory, { withFileTypes: true }).catch(missing)) ?? []).filter(visible);
  const names = [];
  for (const entry of entries) {
    const at = relative(path.join(directory, entry.name));
    if (entry.isSymbolicLink()) fail(`${at} is a symbolic link; generate-skills.mjs does not follow links.`);
    if (!entry.isDirectory()) {
      if (filesAllowed) continue;
      fail(`${at} is not a skill directory; remove it.`);
    }
    if (!SKILL_NAME.test(entry.name)) {
      fail(`${at}: a skill directory name must match ${SKILL_NAME} (lowercase letters, digits and hyphens).`);
    }
    names.push(entry.name);
  }
  return names.sort();
}

async function readSkill(name) {
  const file = path.join(root, name, 'SKILL.md');
  await refuseSymlinks(file);
  return readFile(file, 'utf8');
}

// Files in skills/ (README.md) document it; every directory is a skill.
const names = await skillDirectories(root, { filesAllowed: true });
const skills = await Promise.all(names.map(async name => ({ name, content: await readSkill(name) })));
const source = `// Generated by scripts/generate-skills.mjs from skills/*/SKILL.md. Do not edit.
export interface AgentSkill {
  readonly name: string;
  readonly content: string;
}

export const AGENT_SKILLS: readonly AgentSkill[] = ${JSON.stringify(skills, null, 2)};
`;

const removed = (await skillDirectories(pluginSkills, { filesAllowed: false })).filter(name => !names.includes(name));
await refuseSymlinks(output);
const stale = [];
if ((await readFile(output, 'utf8').catch(() => '')) !== source) {
  stale.push(relative(output));
}
for (const name of removed) {
  stale.push(`${relative(path.join(pluginSkills, name))} (not in skills/)`);
}
for (const skill of skills) {
  const bundled = path.join(pluginSkills, skill.name, 'SKILL.md');
  await refuseSymlinks(bundled);
  if ((await readFile(bundled, 'utf8').catch(() => '')) !== skill.content) stale.push(relative(bundled));
}

if (check) {
  if (stale.length > 0) {
    fail(`Out of date with skills/; run node packages/cli/scripts/generate-skills.mjs:\n  ${stale.join('\n  ')}`);
  }
} else {
  await writeFile(output, source);
  for (const name of removed) {
    // Checked above: a real directory, named like a skill, directly in pluginSkills.
    await rm(path.join(pluginSkills, name), { recursive: true, force: true });
  }
  for (const skill of skills) {
    const directory = path.join(pluginSkills, skill.name);
    await mkdir(directory, { recursive: true });
    await writeFile(path.join(directory, 'SKILL.md'), skill.content);
  }
}
