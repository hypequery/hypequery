import { validateProtocolClientContract, type ClientDimension, type ProtocolClientEndpoint } from '@hypequery/protocol';
import { clientInputType, literal } from './input-types.js';

function dimensionType(definition: ClientDimension): string {
  const wire = definition.wireType === 'number-or-string' ? 'number | string' : definition.wireType;
  return wire + (definition.nullable === false ? '' : ' | null');
}

function endpointType(endpoint: ProtocolClientEndpoint): string {
  const dimensions = Object.keys(endpoint.dimensions).sort().filter(key => endpoint.dimensions[key].groupable)
    .map(key => `readonly ${literal(key)}?: ${dimensionType(endpoint.dimensions[key])};`);
  const measures = Object.keys(endpoint.measures).sort().map(key => `readonly ${literal(key)}?: string | null;`);
  // The physical time column may be nullable; the descriptor makes no non-null guarantee.
  const row = `{ ${[...dimensions, ...measures, ...(endpoint.time ? ['readonly period?: string | null;'] : [])].join('\n')} }`;
  const semantic = {
    version: 1, kind: endpoint.kind, dimensions: Object.fromEntries(Object.keys(endpoint.dimensions).sort().map(key => [key, { wireType: endpoint.dimensions[key].wireType, nullable: endpoint.dimensions[key].nullable }])),
    ...(endpoint.kind === 'dataset' ? { measures: Object.fromEntries(Object.keys(endpoint.measures).sort().map(key => [key, { wireType: 'string', nullable: true }])), defaultMeasures: endpoint.defaultMeasures }
      : { metricName: Object.keys(endpoint.measures)[0] }),
  };
  return `{
    input: ${clientInputType(endpoint)};
    output: { data: ${row}[]; meta?: ClientResponseMeta | null };
    readonly __hypequeryClientSemantic?: ${JSON.stringify(semantic)};
  }`;
}

/** Data-only generator: no API module evaluation, credentials, drivers or server dependencies. */
export function renderClientContract(source: unknown): string {
  const contract = validateProtocolClientContract(source);
  const endpoints = [...contract.endpoints].sort((a, b) => a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
  const entries = endpoints.map(endpoint => ({ endpoint, key: endpoint.kind === 'dataset' ? `dataset:${endpoint.id}` : endpoint.id }));
  return `// Generated by hypequery generate:client. Do not edit.
// Runtime validation still enforces selection dependencies, timezones and query budgets.
export interface ClientResponseMeta {
  requestId: string;
  timingMs: number;
  rowCount: number;
  pagination: { limit: number; offset: number; hasMore: boolean };
  cache?: { hit: boolean };
}
export type ClientApi = {
${entries.map(({ endpoint, key }) => `  ${literal(key)}: ${endpointType(endpoint)};`).join('\n')}
};
export const clientManifest = {
${entries.map(({ endpoint, key }) => `  [${literal(key)}]: { method: 'POST', path: ${literal(endpoint.path)}, schemaHash: ${literal(endpoint.schemaHash)} },`).join('\n')}
} as const;
export const clientContractHash = ${literal(contract.contentHash)} as const;
`;
}
