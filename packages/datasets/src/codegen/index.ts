/**
 * `@hypequery/datasets/codegen`: a deployment contract as the TypeScript that
 * builds it (decision 0020 §3).
 *
 * The output is idiomatic `dataset()` code, a `datasets.ts` and the
 * `cloud.ts` entrypoint `hypequery deploy` reads, and `publishToCloud` over it
 * builds the same contract as the input, with its members in name order (the
 * only order code produces; see `canonicalMemberOrder`). That round trip is
 * the guarantee: anything the authoring API can't reproduce exactly is
 * refused with `ContractExportError` instead of being approximated.
 */

import { validateProtocolDeploymentContract } from '@hypequery/protocol';

import { compareStrings } from '../utils/canonical-json.js';
import { cloudSource } from './cloud-source.js';
import { datasetSource } from './dataset-source.js';
import { declarationOrder } from './utils/declaration-order.js';
import { canonicalMemberOrder } from './utils/member-order.js';
import { datasetConstantNames } from './utils/naming.js';
import { ContractExportError } from './errors.js';
import { literal, propertyKey } from './utils/source-writer.js';

export { ContractExportError, canonicalMemberOrder };

export interface GenerateDatasetSourceOptions {
  /** Comment lines at the top of each file, without `//`. */
  readonly header?: readonly string[];
  /** Module the code imports from; `@hypequery/datasets` unless a test points it elsewhere. */
  readonly importSource?: string;
}

export interface GeneratedDatasetSource {
  /** File path relative to the output directory, and its contents. */
  readonly files: Readonly<Record<'datasets.ts' | 'cloud.ts', string>>;
  /** The file `hypequery deploy` takes. */
  readonly entrypoint: 'cloud.ts';
}

const DEFAULT_HEADER = [
  'Generated by hypequery from a deployment contract.',
  'This code is now the source of the model: edit it here and deploy with `npx hypequery deploy`.',
];

export function generateDatasetSource(
  contract: unknown,
  options: GenerateDatasetSourceOptions = {},
): GeneratedDatasetSource {
  // Code can only produce members in name order (see `canonicalMemberOrder`).
  const validated = canonicalMemberOrder(validateProtocolDeploymentContract(contract));
  const importSource = options.importSource ?? '@hypequery/datasets';
  const header = (options.header ?? DEFAULT_HEADER).map(line => `// ${line}`.trimEnd()).join('\n');
  const datasets = validated.datasets;
  if (!datasets.some(dataset => dataset.endpoint !== undefined)) {
    throw new ContractExportError(
      String(datasets[0]?.name ?? '(none)'),
      'the deployment',
      'publishToCloud needs at least one dataset with an endpoint',
    );
  }
  const constants = datasetConstantNames(datasets.map(dataset => String(dataset.name)));

  const order = declarationOrder(datasets);
  const earlier = new Set<string>();
  const sources = order.map(dataset => {
    const source = datasetSource(dataset, constants, new Set(earlier));
    earlier.add(String(dataset.name));
    return source;
  });
  const imports = [...new Set(sources.flatMap(source => [...source.imports]))]
    .sort((left, right) => compareStrings(left.replace(/^type /, ''), right.replace(/^type /, '')));
  const registry = datasets
    .filter(dataset => dataset.endpoint !== undefined)
    .map(dataset => `  ${propertyKey(String(dataset.name))}: ${constants.get(String(dataset.name))},`);

  const datasetsFile = [
    header,
    '',
    `import { ${imports.join(', ')} } from ${literal(importSource)};`,
    '',
    sources.map(source => source.code).join('\n'),
    '/** The datasets published with an endpoint. */',
    registry.length > 0 ? `export const datasets = {\n${registry.join('\n')}\n};` : 'export const datasets = {};',
    '',
  ].join('\n');

  const cloud = cloudSource(datasets, constants, importSource);
  return {
    files: { 'datasets.ts': datasetsFile, 'cloud.ts': `${header}\n\n${cloud.code}` },
    entrypoint: 'cloud.ts',
  };
}
