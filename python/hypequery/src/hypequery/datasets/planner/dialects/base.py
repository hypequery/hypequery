"""What compilation needs from a SQL dialect.

Features resolve names, allocate parameters and decide structure; a dialect
decides only spelling. Every operand a dialect receives is already safe SQL —
a quoted identifier, an allocated placeholder, or a trusted expression — so a
dialect never sees, and never has to escape, a caller's value.

Mirrors `SqlDialect` in `@hypequery/clickhouse`. ClickHouse is the only
implementation today; a second dialect must reproduce the semantics the
ClickHouse one documents, not merely its syntax.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Protocol

if TYPE_CHECKING:
    from ...dimensions import DimensionType
    from ...measures import Measure
    from ..aggregates import AggregateCall
    from ..query_node import DatasetSelectNode


class TimeSqlDialect(Protocol):
    """Spellings for window and shift measure statements (RFC 0015)."""

    def start_of(self, time: str, grain: str) -> str: ...
    def start_of_in_zone(self, time: str, grain: str, timezone: str) -> str: ...
    def add_time(self, time: str, amount: str | int, grain: str) -> str: ...
    def subtract_time(self, time: str, amount: int, grain: str) -> str: ...
    def time_diff(self, grain: str, start: str, end: str) -> str: ...
    def parse_timestamp(self, expression: str, timezone: str) -> str: ...
    def timezone_of(self, time: str) -> str: ...
    def clock_part(self, part: str, time: str) -> str: ...
    def is_date_only_type(self, expression: str) -> str: ...
    def guard(self, condition: str, message: str) -> str:
        """An expression that raises *message* when *condition* holds, else 0."""
        ...

    def if_else(self, condition: str, then: str, otherwise: str) -> str: ...
    def greatest(self, *expressions: str) -> str: ...
    def least(self, *expressions: str) -> str: ...
    def is_not_distinct_from(self, left: str, right: str) -> str: ...
    def assume_not_null(self, expression: str) -> str: ...
    def to_nullable(self, expression: str) -> str: ...
    def count_if(self, condition: str) -> str: ...
    def series_index(self, count: str) -> str:
        """One row per index in `range(count)`."""
        ...

    def any_index(self, index: str, count: str, predicate: str) -> str: ...
    def pack_row(self, expressions: list[str]) -> str: ...
    def row_element(self, row: str, position: int) -> str: ...
    def filtered_input(self, condition: str, expression: str, fallback: str) -> str: ...
    def window_aggregate(self, measure: Measure, expression: str, arg: str) -> str: ...
    def reaggregate(self, aggregation: str, expression: str) -> str: ...


class SqlDialect(TimeSqlDialect, Protocol):
    @property
    def name(self) -> str: ...

    def parameter_type(self, field_type: DimensionType) -> str:
        """The parameter type a filter value on a dimension of *field_type* binds as."""
        ...

    def aggregate(self, name: str, measure: Measure, target: str, arg: str | None) -> AggregateCall:
        """The aggregate call for *measure* over already-resolved input SQL."""
        ...

    def conditional(self, aggregate: AggregateCall, condition: str) -> AggregateCall:
        """*aggregate* restricted to the rows where *condition* holds."""
        ...

    def truncate_to_grain(self, grain: str, column: str) -> str:
        """*column* truncated to the start of its *grain* bucket."""
        ...

    def period_text(self, bucket: str) -> str:
        """A grain bucket rendered as RFC 0015's period text."""
        ...

    def in_time_zone(self, column: str, zone_placeholder: str) -> str:
        """*column* read as an instant in the bound zone."""
        ...

    def divide(self, left: str, right: str) -> str:
        """*left* divided by *right* without truncating to either operand's scale."""
        ...

    def not_null(self, expression: str) -> str: ...

    def match_marker(self, alias: str) -> str:
        """A projected column that is non-null exactly when a join matched."""
        ...

    def when(self, condition: str, expression: str) -> str:
        """*expression* where *condition* holds, else NULL."""
        ...

    def row_count(self) -> str: ...

    def resolved_source(self, source: str) -> str:
        """*source*, with any alias, read with superseded row versions resolved (RFC 0021)."""
        ...

    def resolved_rows_settings(self) -> str:
        """The settings every statement reading a resolved source must pin."""
        ...

    def distinct_count(self, columns: list[str]) -> str:
        """The exact number of distinct (possibly composite) keys over *columns*."""
        ...

    def render_select(self, node: DatasetSelectNode) -> str: ...
