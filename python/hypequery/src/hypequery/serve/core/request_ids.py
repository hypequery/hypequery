"""Request identifiers: the server's authoritative id and a caller's correlation id.

The authoritative id is generated by the server for each request. A caller's
own id is never authoritative; it is echoed only as `x-correlation-id`, after
passing the same grammar and bound as TypeScript serve.
"""

from __future__ import annotations

import re
import secrets

from .messages import Headers, ServeResponse

#: TypeScript serve's bound and grammar for an external correlation id: small,
#: printable ASCII that cannot split a header or forge a log line.
MAX_CORRELATION_ID_BYTES = 200
_CORRELATION_ID = re.compile(r"[A-Za-z0-9][A-Za-z0-9._:/-]*")


def new_request_id() -> str:
    return secrets.token_hex(16)


def sanitize_correlation_id(value: str | None) -> str | None:
    """A caller's correlation id if it is safe to echo and log, else None."""

    if value is None:
        return None
    candidate = value.strip()
    if len(candidate.encode("utf-8")) > MAX_CORRELATION_ID_BYTES:
        return None
    return candidate if _CORRELATION_ID.fullmatch(candidate) else None


def correlation_id(headers: Headers) -> str | None:
    """The caller's `x-request-id`, when there is exactly one and it is safe."""

    values = headers.getlist("x-request-id")
    return sanitize_correlation_id(values[0]) if len(values) == 1 else None


def with_request_ids(response: ServeResponse, request_id: str, headers: Headers) -> ServeResponse:
    """*response* carrying the server's id, and the caller's only when valid.

    Whatever a handler set is replaced: the server's id is the only one a
    client or a log should ever correlate on.
    """

    stamped = response.without_headers("x-correlation-id").with_headers(
        {"x-request-id": request_id}
    )
    correlation = correlation_id(headers)
    if correlation is not None:
        stamped = stamped.with_headers({"x-correlation-id": correlation})
    return stamped
