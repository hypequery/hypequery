"""Request identifiers: the server's authoritative id and a caller's correlation id.

The authoritative id is generated by the HTTP security profile's middleware and
kept under a key only this package holds. A caller's own id is never
authoritative; it is echoed only after passing the same grammar and bound as
TypeScript serve (`core/request_ids.py`).
"""

from __future__ import annotations

from fastapi import Request

from .core.request_ids import MAX_CORRELATION_ID_BYTES, new_request_id, sanitize_correlation_id
from .utils.scope_slot import ScopeSlot

__all__ = [
    "MAX_CORRELATION_ID_BYTES",
    "REQUEST_ID_SLOT",
    "ensure_request_id",
    "request_id",
    "sanitize_correlation_id",
]

#: Only this package holds the slot, so no middleware or handler that does not
#: import it can plant a request id where `request_id()` reads one.
REQUEST_ID_SLOT: ScopeSlot[str] = ScopeSlot(str)


def request_id(request: Request) -> str | None:
    """The authoritative, server-generated id of *request*, when installed."""

    return REQUEST_ID_SLOT.get(request.scope)


def ensure_request_id(request: Request) -> str:
    """Reuse the profile's id, or establish one for a standalone error path."""

    return REQUEST_ID_SLOT.setdefault(request.scope, new_request_id)
