"""Business context v1: the shared fixtures, and what JSON cannot describe."""

from __future__ import annotations

import hashlib
import json
from collections import OrderedDict
from pathlib import Path
from typing import cast

import pytest

from hypequery.protocol import (
    DEFAULT_PROTOCOL_BUSINESS_CONTEXT_LIMITS,
    PROTOCOL_BUSINESS_CONTEXT_IDENTITY_DOMAIN,
    ProtocolBusinessContextError,
    ProtocolBusinessContextLimits,
    encode_protocol_business_context,
    encode_protocol_business_context_to_string,
    hash_protocol_business_context,
    is_empty_protocol_business_context,
    prepare_protocol_business_context,
    validate_protocol_business_context,
)

FIXTURES = (
    Path(__file__).resolve().parents[3]
    / "specs"
    / "security-protocol"
    / "fixtures"
    / "business-context-v1"
)
LIMIT_FIELDS = {
    "maxTextLength": "max_text_length",
    "maxItems": "max_items",
    "maxBytes": "max_bytes",
}
HEADER: dict[str, object] = {"kind": "hypequery-business-context", "version": 1}


def _fixtures(name: str) -> list[dict[str, object]]:
    return cast(list[dict[str, object]], json.loads((FIXTURES / f"{name}.json").read_text()))


SUCCESS = _fixtures("success")
REJECTIONS = _fixtures("rejections")
IDENTITIES = _fixtures("identity")


def _limits(case: dict[str, object]) -> ProtocolBusinessContextLimits:
    configured = cast(dict[str, int], case.get("limits") or {})
    return ProtocolBusinessContextLimits(
        **{LIMIT_FIELDS[key]: value for key, value in configured.items()}
    )


def _failure(value: object, limits: ProtocolBusinessContextLimits | None = None) -> str:
    with pytest.raises(ProtocolBusinessContextError) as raised:
        prepare_protocol_business_context(
            value, limits=limits or DEFAULT_PROTOCOL_BUSINESS_CONTEXT_LIMITS
        )
    return f"{raised.value.code} {raised.value.path}"


# Shared fixtures, generated by the TypeScript reference -------------------


def test_every_success_case_has_an_identity() -> None:
    assert [case["id"] for case in IDENTITIES] == [case["id"] for case in SUCCESS]


@pytest.mark.parametrize("case", IDENTITIES, ids=lambda case: cast(str, case["id"]))
def test_canonical_bytes_and_identity_match_typescript(case: dict[str, object]) -> None:
    source = next(item for item in SUCCESS if item["id"] == case["id"])
    prepared = prepare_protocol_business_context(source["value"])
    assert prepared.canonical == case["canonical"]
    assert prepared.context_bytes == prepared.canonical.encode("utf-8")
    assert prepared.identity == case["sha256"]
    assert is_empty_protocol_business_context(prepared.context) is source["empty"]


@pytest.mark.parametrize("case", REJECTIONS, ids=lambda case: cast(str, case["id"]))
def test_rejections_match_typescript_code_and_path(case: dict[str, object]) -> None:
    assert _failure(case["value"], _limits(case)) == f"{case['error']} {case['path']}"


# Canonical form --------------------------------------------------------------


def test_validation_returns_the_canonical_document_in_field_order() -> None:
    document = validate_protocol_business_context(
        {
            "caveats": [" Refunds live elsewhere. "],
            "glossary": [{"meaning": " A paying account. ", "term": " Workspace "}],
            "goals": [],
            "summary": " Shop ",
            **HEADER,
        }
    )
    assert list(document) == ["kind", "version", "summary", "glossary", "caveats"]
    assert document == {
        "kind": "hypequery-business-context",
        "version": 1,
        "summary": "Shop",
        "glossary": [{"term": "Workspace", "meaning": "A paying account."}],
        "caveats": ["Refunds live elsewhere."],
    }


def test_identity_is_domain_separated_sha256_of_the_canonical_bytes() -> None:
    value = {**HEADER, "summary": "Shop"}
    canonical = encode_protocol_business_context_to_string(value)
    assert encode_protocol_business_context(value) == canonical.encode("utf-8")
    expected = hashlib.sha256(
        PROTOCOL_BUSINESS_CONTEXT_IDENTITY_DOMAIN.encode("utf-8") + canonical.encode("utf-8")
    ).hexdigest()
    assert hash_protocol_business_context(value) == expected
    assert PROTOCOL_BUSINESS_CONTEXT_IDENTITY_DOMAIN.endswith("\0")


def test_a_float_version_one_is_version_one() -> None:
    # JSON readers that keep `1.0` as a float still name version 1.
    assert validate_protocol_business_context({**HEADER, "version": 1.0})["version"] == 1


def test_a_split_surrogate_pair_is_the_character_it_spells() -> None:
    # JavaScript cannot tell these apart, so neither may the identity.
    split = validate_protocol_business_context({**HEADER, "summary": "Up \ud83d\udcc8"})
    joined = validate_protocol_business_context({**HEADER, "summary": "Up \U0001f4c8"})
    assert split == joined
    assert hash_protocol_business_context(
        {**HEADER, "summary": "Up \ud83d\udcc8"}
    ) == hash_protocol_business_context({**HEADER, "summary": "Up \U0001f4c8"})


# Host objects JSON cannot describe ------------------------------------------


@pytest.mark.parametrize(
    ("value", "expected"),
    [
        (OrderedDict(HEADER), "HQ_BUSINESS_CONTEXT_UNSAFE_OBJECT $"),
        ({**cast(dict[object, object], HEADER), 1: "x"}, "HQ_BUSINESS_CONTEXT_UNSAFE_OBJECT $"),
        ({**HEADER, "goals": ("Grow",)}, "HQ_BUSINESS_CONTEXT_UNSAFE_OBJECT $.goals"),
        ({**HEADER, "goals": {"Grow"}}, "HQ_BUSINESS_CONTEXT_UNSAFE_OBJECT $.goals"),
        (
            {**HEADER, "kpis": [OrderedDict(name="ARR", definition="x")]},
            "HQ_BUSINESS_CONTEXT_UNSAFE_OBJECT $.kpis[0]",
        ),
        (
            {**HEADER, "kpis": [{"name": "ARR", "definition": "x", 2: "y"}]},
            "HQ_BUSINESS_CONTEXT_UNSAFE_OBJECT $.kpis[0]",
        ),
        # Text that is not a string is a type error, whatever object it is.
        ({**HEADER, "summary": b"bytes"}, "HQ_BUSINESS_CONTEXT_TYPE $.summary"),
    ],
)
def test_host_objects_are_refused(value: object, expected: str) -> None:
    assert _failure(value) == expected


def test_a_str_subclass_is_not_text() -> None:
    class Text(str):
        __slots__ = ()

    assert _failure({**HEADER, "summary": Text("Shop")}) == "HQ_BUSINESS_CONTEXT_TYPE $.summary"


# Limits ---------------------------------------------------------------------


def test_limits_may_tighten_but_never_raise_the_v1_ceilings() -> None:
    ceilings = ProtocolBusinessContextLimits(
        max_text_length=4_096, max_items=100, max_bytes=1_048_576
    )
    assert ceilings == DEFAULT_PROTOCOL_BUSINESS_CONTEXT_LIMITS
    for field, value in (
        ("max_text_length", 4_097),
        ("max_items", 0),
        ("max_bytes", 1_048_577),
        ("max_items", True),
    ):
        with pytest.raises(ValueError, match=field):
            ProtocolBusinessContextLimits(**{field: value})


def test_the_canonical_byte_limit_applies_to_the_whole_document() -> None:
    goals = ["x" * 4_096] * 100
    glossary = [{"term": f"Term {index}", "meaning": "y" * 4_096} for index in range(100)]
    huge = {**HEADER, "goals": goals, "glossary": glossary, "caveats": goals}
    # Every value is within its own limits, so only encoding can refuse it.
    validate_protocol_business_context(huge)
    assert _failure(huge) == "HQ_BUSINESS_CONTEXT_TOO_LARGE $"
